    id_commande INTEGER NOT NULL,
    id_plat INTEGER NOT NULL,
    quantite INTEGER NOT NULL,

    PRIMARY KEY (id_commande, id_plat),

    FOREIGN KEY (id_commande)
        REFERENCES commande(id_commande),

    FOREIGN KEY (id_plat)
